# Multiple assignment of different values
a, b, c = 10, 20, 30

print("Values after multiple assignment:")
print("a =", a)
print("b =", b)
print("c =", c)

# Assigning the same value to all variables in one line
x = y = z = 100

print("\nValues after assigning the same value:")
print("x =", x)
print("y =", y)
print("z =", z)